/* Search (⌘K / "/"): our modal over a Pagefind full-text index. pagefind.js and
   the index load lazily on first open. If the index is missing (a bare
   `hugo server` without the second build step) the modal shows a quiet hint.

   The bundle URL comes from Hugo (window.TAIGA_PAGEFIND, built with relURL by the
   js-bridge partial): a literal "/pagefind/pagefind.js" 404s on a site served from
   a subpath, and the catch below would swallow it as "index not built". Pagefind
   picks the language index off <html lang> on its own — the one baseof already
   sets — so an English reader never gets Russian hits.

   The import specifier is a variable on purpose: esbuild leaves a non-literal
   dynamic import alone, which is what we want — pagefind.js is generated by the
   second build step and must not be resolved at bundle time.

   ZERO STATE. Before the first keystroke the modal is not empty: it shows what
   this reader opened before, then the newest guides. Those come from a manifest
   Hugo publishes (window.TAIGA_SEARCH_INDEX — search/manifest.html), not from
   Pagefind, for three reasons: it is the same list the feed renders, so the two
   cannot drift; it resolves taiga.visited, which stores paths and not titles, and
   a path from a year ago must still find its title; and it arrives whether or not
   the Pagefind index was ever built, which is what makes the modal useful under a
   bare `hugo server`. Searching itself still needs Pagefind — only the zero state
   does not. */
import { I18N } from './i18n.js';

const PAGEFIND_URL = (typeof window !== 'undefined' && window.TAIGA_PAGEFIND) || '/pagefind/pagefind.js';
const MANIFEST_URL = (typeof window !== 'undefined' && window.TAIGA_SEARCH_INDEX) || '';

/* The zero state's budget, in rows. It is a budget and not two fixed caps
   because the sections trade: a reader with no history gets the whole of it
   spent on new guides instead of a short panel with a hole where their past
   would be. History is capped at three regardless — past three, "recently" is
   just a list. The total is what fits the list without turning the modal into a
   second home page. */
const ROWS_MAX = 7;
const RECENT_MAX = 3;
const LATEST_MIN = 3;

let smBack = null, smInput = null, smList = null, smFoot = null, smItems = [], smEls = [], smSel = 0;
/* Every path that ends in drawing the list takes a ticket first and re-checks it
   after each await; a stale one draws nothing. Both paths share the counter,
   because they race each OTHER as much as themselves: the zero state waits on
   the manifest while a query waits on Pagefind, and either can come back to a
   panel the reader has already moved past — typing before the manifest lands,
   or clearing the field before the hits do. */
let seq = 0;
let pagefind = null, pfState = 'idle'; /* idle | loading | ready | missing */
let manifest = null, mfState = 'idle'; /* idle | loading | ready | missing */

function esc(s) { return String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;'); }

function build() {
  if (smBack) return;
  smBack = document.createElement('div'); smBack.className = 'sm-back'; smBack.hidden = true;
  smBack.innerHTML = '<div class="sm" role="dialog" aria-label="' + esc(I18N.searchAria) + '">' +
    '<div class="sm-in"><svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round"><circle cx="11" cy="11" r="7"/><path d="m21 21-4.2-4.2"/></svg>' +
    '<input type="text" placeholder="' + esc(I18N.searchPlaceholder) + '" spellcheck="false"></div>' +
    '<div class="sm-list"></div>' +
    '<div class="sm-foot" hidden></div></div>';
  document.body.appendChild(smBack);
  smInput = smBack.querySelector('input'); smList = smBack.querySelector('.sm-list');
  smFoot = smBack.querySelector('.sm-foot');
  smBack.addEventListener('mousedown', function (e) { if (e.target === smBack) closeSearch(); });
  smInput.addEventListener('input', function () { runSearch(smInput.value); });
  smInput.addEventListener('keydown', function (e) {
    if (e.key === 'ArrowDown') { e.preventDefault(); moveSel(1); }
    else if (e.key === 'ArrowUp') { e.preventDefault(); moveSel(-1); }
    else if (e.key === 'Enter') { e.preventDefault(); const it = smItems[smSel]; if (it) location.href = it.url; }
  });
}

async function ensurePagefind() {
  if (pfState === 'ready' || pfState === 'missing') return;
  pfState = 'loading';
  try {
    pagefind = await import(/* @vite-ignore */ PAGEFIND_URL);
    await pagefind.init();
    pfState = 'ready';
  } catch (e) {
    pfState = 'missing';
  }
}

/* The manifest is fetched once per page load and kept — it is a few KB, and the
   modal is opened more than once in a session. A failure is not worth a message:
   the zero state simply falls back to the placeholder line it showed before. */
async function ensureManifest() {
  if (mfState === 'ready' || mfState === 'missing') return;
  if (!MANIFEST_URL) { mfState = 'missing'; return; }
  mfState = 'loading';
  try {
    const r = await fetch(MANIFEST_URL);
    if (!r.ok) throw new Error(r.status);
    const rows = await r.json();
    manifest = Array.isArray(rows) ? rows : [];
    mfState = 'ready';
  } catch (e) {
    mfState = 'missing';
  }
}

function foot(on) { if (smFoot) { smFoot.textContent = on ? I18N.searchHint : ''; smFoot.hidden = !on; } }

function empty(msg) { smList.innerHTML = '<div class="sm-empty">' + esc(msg) + '</div>'; smItems = []; smEls = []; foot(false); }

/* One result row, shared by the zero state and the hit list. `excerpt` is
   Pagefind's own HTML (it carries the <mark>s) and is trusted as such; every
   other field is escaped. A zero-state row has no excerpt — it is a title, a
   breadcrumb and a reading time, which is what keeps the panel a list. */
function row(it, i) {
  const a = document.createElement('a');
  a.className = 'sm-item' + (i === smSel ? ' sel' : '');
  a.href = it.url;
  a.innerHTML = '<div class="t">' + esc(it.title) + '</div>' +
    (it.excerpt ? '<span class="d">' + it.excerpt + '</span>' : '') +
    (it.crumb ? '<span class="k"><b>' + esc(it.crumb) + '</b>' + (it.mins ? ' · ' + esc(it.mins) + ' ' + I18N.minutes : '') + '</span>' : '');
  a.addEventListener('mousemove', function () { const n = smEls.indexOf(a); if (n >= 0 && smSel !== n) { smSel = n; paintSel(); } });
  return a;
}

function head(text, tail) {
  const h = document.createElement('div');
  h.className = 'sm-head';
  h.innerHTML = esc(text) + (tail ? '<span class="n">' + esc(tail) + '</span>' : '');
  return h;
}

/* Guides this reader opened, newest first. taiga.visited (modules/visited.js) is
   a list of paths in the order they were last opened, so the tail is the recent
   end. `exclude` arrives already carrying the page we are standing on, and
   collects what this section spends, so neither is offered twice below.
   A path that no longer resolves (an unpublished guide, a renamed URL, another
   language's path in this language's manifest) simply falls out. */
function recent(byPath, exclude) {
  let paths = [];
  try { paths = JSON.parse(localStorage.getItem('taiga.visited') || '[]'); } catch (e) { paths = []; }
  const out = [];
  for (let i = paths.length - 1; i >= 0 && out.length < RECENT_MAX; i--) {
    const p = paths[i];
    if (exclude[p]) continue;
    const g = byPath[p];
    if (g) { out.push(g); exclude[p] = 1; }
  }
  return out;
}

/* The zero state: history, then what is new. Sections that would be empty are
   not drawn — a first-time reader sees one list, not a heading over a void. */
async function renderZero(my) {
  if (my === undefined) my = ++seq;
  await ensureManifest();
  if (my !== seq) return;
  if (mfState !== 'ready' || !manifest.length) { empty(I18N.searchPlaceholder); return; }

  const byPath = {};
  manifest.forEach(function (g) { byPath[g.u] = g; });
  /* Seeded with the page we are standing on, so it is out of BOTH sections:
     offering the reader what they already have open is offering nothing, and in
     "latest" — where a just-published guide is also the one being read — it
     spends a row of the budget on a link back to here. */
  const seen = {};
  seen[location.pathname] = 1;
  const secs = [];

  const rec = recent(byPath, seen);
  if (rec.length) secs.push({ head: I18N.searchRecent, tail: '', rows: rec });

  const latestMax = Math.max(LATEST_MIN, ROWS_MAX - rec.length);
  const latest = [];
  for (let i = 0; i < manifest.length && latest.length < latestMax; i++) {
    const g = manifest[i];
    if (seen[g.u]) continue;
    latest.push(g); seen[g.u] = 1;
  }
  if (latest.length) {
    secs.push({
      head: I18N.searchLatest,
      tail: String(I18N.searchTotal || '').replace('{n}', manifest.length),
      rows: latest,
    });
  }

  smItems = []; smEls = []; smSel = 0;
  smList.innerHTML = '';
  secs.forEach(function (s) {
    smList.appendChild(head(s.head, s.tail));
    s.rows.forEach(function (g) {
      const it = { url: g.u, title: g.t, crumb: g.c, mins: g.m, excerpt: '' };
      const a = row(it, smItems.length);
      smItems.push(it); smEls.push(a);
      smList.appendChild(a);
    });
  });
  foot(true);
  paintSel();
}

async function runSearch(q) {
  q = (q || '').trim();
  const my = ++seq;
  /* An emptied field goes home: the same zero state, so the panel is somewhere
     you can arrow back to rather than a screen you lose by deleting a word. It
     carries this call's ticket, so a slow manifest cannot land on top of hits
     the reader asked for afterwards. */
  if (!q) { renderZero(my); ensurePagefind(); return; }
  await ensurePagefind();
  if (my !== seq) return;
  if (pfState === 'missing') { empty(I18N.searchUnbuilt); return; }
  if (pfState !== 'ready') return;
  const search = await pagefind.search(q);
  if (my !== seq) return;
  const results = await Promise.all(search.results.slice(0, 12).map(function (r) { return r.data(); }));
  if (my !== seq) return;
  smItems = results.map(function (d) {
    const meta = d.meta || {};
    return { url: d.url, title: meta.title || d.url, excerpt: d.excerpt, crumb: meta.crumb, mins: meta.mins };
  });
  smSel = 0;
  if (!smItems.length) { empty(I18N.searchEmpty); return; }
  foot(false);
  smEls = [];
  smList.innerHTML = '';
  smItems.forEach(function (it, i) {
    const a = row(it, i);
    smEls.push(a);
    smList.appendChild(a);
  });
}

function paintSel() {
  smEls.forEach(function (el, i) { el.classList.toggle('sel', i === smSel); });
  const el = smEls[smSel]; if (el) el.scrollIntoView({ block: 'nearest' });
}
function moveSel(d) { if (!smItems.length) return; smSel = (smSel + d + smItems.length) % smItems.length; paintSel(); }

export function openSearch() { build(); smBack.hidden = false; smInput.value = ''; runSearch(''); smInput.focus(); }
export function closeSearch() { if (smBack) smBack.hidden = true; }
